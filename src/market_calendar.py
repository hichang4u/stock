"""KRX가 정규 시각(09:00)보다 늦게 여는 날 — 봇이 그날 진입하지 않는다.

봇의 시각(장전 프로브 08:59:45, F1 09:00, 첫 체결 대기, 진입 마감 09:11,
F5 15:15 등)은 모두 09:00 개장을 전제로 한다. 10:00에 여는 날에는 그 시각이
장전 동시호가 한가운데라, 후보가 있으면 동시호가에 주문이 들어가고 취소가
늦으면 10:00에 체결될 수 있다. 2026-11-19 수능일에는 후보가 없어 주문이
나가지 않았다(docs/DAILY_LOG_ANALYSIS_20261119.md 4절). 그래서 그날은 진입
경로만 멈춘다(같은 문서 8절의 나, 2026-11-19 결정). 청산(F5)은 막지 않는다 —
전날 포지션이 남는 비정상 상황에서도 청산 경로는 살아 있어야 한다.

이 목록은 시장 달력 자료다. KIS 휴장일 조회처럼 "그날 장이 어떤가"를 말할
뿐이고, 다른 날의 매매 규칙은 바꾸지 않는다. 그래서 이 파일은 전략 지문
(`src/release.py`의 `_STRATEGY_FILES`)에 넣지 않는다. 날짜를 더해도 지문이
바뀌지 않는다. "목록에 있는 날은 진입하지 않는다"는 규칙은 `main.py`에 있고
지문에 든다.

KIS 휴장일 조회(CTCA0903R)는 개장 여부만 주고 개장 시각은 주지 않는다.
날짜는 KRX 공지를 보고 손으로 더한다. 해마다 할 일: 그해 수능일과 다음 해
첫 거래일을 KRX 공지로 확인해 여기에 넣는다.
"""

# 날짜(YYYYMMDD) → 사유. 지난 날짜는 기록으로 남긴다(지워도 동작은 같다).
LATE_OPEN_DAYS: dict[str, str] = {
    "20261119": "수능일 — KRX 10:00 ~ 16:30 운영(2026-11-19 실측)",
    # KRX는 해마다 첫 거래일을 10:00에 연다(2026-01-02도 10:00 개장).
    # 2027년 공지는 아직 확인하지 않았다.
    "20270104": "2027년 첫 거래일 — 10:00 개장(KRX 관행. 공지로 확인할 것)",
}


def late_open_reason(date: str) -> str | None:
    """그날이 늦게 여는 날이면 사유, 아니면 None. `date`는 YYYYMMDD."""
    return LATE_OPEN_DAYS.get(date)


def is_late_open(date: str) -> bool:
    return date in LATE_OPEN_DAYS
